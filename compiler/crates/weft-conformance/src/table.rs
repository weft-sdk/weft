//! The compatibility table: what each language was shown to do, and which pairs were shown to talk.

use std::collections::BTreeMap;
use std::fmt::Write;

use crate::pairs::PairResult;
use crate::RunnerReport;

/// The area of a case: its id up to the first dot (`encoding`, `messaging`, `cross`).
fn area(id: &str) -> &str {
    id.split('.').next().unwrap_or(id)
}

/// Markdown: one row per area of single-runner cases with a column per language, then a matrix of the
/// pair cases that passed for each ordered pair of languages. Only what the run showed is claimed.
pub fn render(reports: &[RunnerReport], pairs: &[PairResult]) -> String {
    let mut out = String::new();
    let langs: Vec<String> = reports
        .iter()
        .map(|r| format!("{} {}", r.language, r.version))
        .collect();

    out.push_str("# Compatibility\n\n");
    out.push_str("Generated by `weft-conformance run --table`. Each cell is the cases that passed out of the cases run.\n\n");
    out.push_str("## Every language, by itself\n\n");
    let _ = writeln!(out, "| Area | {} |", langs.join(" | "));
    let _ = writeln!(out, "| --- |{}", " --- |".repeat(reports.len()));
    let mut areas: BTreeMap<&str, Vec<(usize, usize)>> = BTreeMap::new();
    for (i, r) in reports.iter().enumerate() {
        for res in &r.results {
            let cells = areas
                .entry(area(&res.id))
                .or_insert_with(|| vec![(0, 0); reports.len()]);
            cells[i].1 += 1;
            if res.passed {
                cells[i].0 += 1;
            }
        }
    }
    for (name, cells) in &areas {
        let row: Vec<String> = cells.iter().map(|(p, t)| format!("{p} / {t}")).collect();
        let _ = writeln!(out, "| {name} | {} |", row.join(" | "));
    }

    let ran: Vec<&PairResult> = pairs.iter().filter(|p| !p.skipped).collect();
    out.push_str("\n## One language talking to another\n\n");
    if ran.is_empty() {
        out.push_str(
            "Not run: it needs real infrastructure (a Kafka broker, `WEFT_TEST_KAFKA`).\n",
        );
        return out;
    }
    out.push_str(
        "Rows are the language that sends or calls, columns the one that receives or serves.\n\n",
    );
    let names: Vec<String> = reports.iter().map(|r| r.runner.clone()).collect();
    let _ = writeln!(out, "| caller \\ server | {} |", names.join(" | "));
    let _ = writeln!(out, "| --- |{}", " --- |".repeat(names.len()));
    for caller in &names {
        let cells: Vec<String> = names
            .iter()
            .map(|server| {
                let these: Vec<_> = ran
                    .iter()
                    .filter(|p| &p.caller == caller && &p.server == server)
                    .collect();
                let passed = these.iter().filter(|p| p.passed).count();
                format!("{passed} / {}", these.len())
            })
            .collect();
        let _ = writeln!(out, "| {caller} | {} |", cells.join(" | "));
    }
    let skipped = pairs.iter().filter(|p| p.skipped).count();
    if skipped > 0 {
        let _ = writeln!(
            out,
            "\n{skipped} pair case(s) were skipped for lack of infrastructure and are not counted."
        );
    }
    out
}
