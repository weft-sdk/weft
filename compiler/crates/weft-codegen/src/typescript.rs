/// Generate `weft.gen.ts` for the given packages.
pub fn typescript(irs: &[Ir], options: &Options) -> Result<String, Vec<CodegenError>> {
    let g = Gen::new(irs, options);
    g.run()
}

struct Gen<'a> {
    irs: &'a [Ir],
    options: &'a Options,
    errors: Vec<CodegenError>,
}

impl<'a> Gen<'a> {
    fn new(irs: &'a [Ir], options: &'a Options) -> Self {
        Gen {
            irs,
            options,
            errors: Vec::new(),
        }
    }

    fn fail(&mut self, message: String, help: &str) {
        self.errors.push(CodegenError {
            message,
            help: Some(help.to_string()),
        });
    }

    fn run(mut self) -> Result<String, Vec<CodegenError>> {
        self.check_names();
        if !self.errors.is_empty() {
            return Err(self.errors);
        }

        let mut out = String::new();
        let packages: Vec<&str> = self.irs.iter().map(|i| i.package.as_str()).collect();
        let _ = writeln!(
            out,
            "// Generated by {}. Do not edit: change the contracts and run `weft gen`.",
            self.options.generator
        );
        let _ = writeln!(out, "// Contracts: {}.", packages.join(", "));
        out.push_str("/* eslint-disable */\n");
        let facade = self.facade_plan();
        if let Some(plan) = &facade {
            plan.imports(&mut out);
        }
        out.push('\n');
        out.push_str(
            "/** A uuid. Branded so that an arbitrary string does not type-check as one. */\n",
        );
        out.push_str("export type Uuid = string & { readonly __weft: \"uuid\" };\n");

        for ir in self.irs {
            out.push('\n');
            self.package(&mut out, ir);
        }

        out.push_str("\n/** The checked contracts, which the Weft runtime reads to validate and encode. */\n");
        out.push_str("export const contracts = {\n");
        let entries: Vec<String> = self
            .irs
            .iter()
            .map(|ir| {
                let json = serde_json::to_string_pretty(ir).expect("the IR always serialises");
                let indented: Vec<String> = json.lines().map(|l| format!("  {l}")).collect();
                format!("  {}: {}", ir.package, indented.join("\n").trim_start())
            })
            .collect();
        out.push_str(&entries.join(",\n"));
        out.push_str(",\n} as const;\n");

        if let Some(plan) = &facade {
            self.facade(&mut out, plan);
        }

        if self.errors.is_empty() {
            Ok(out)
        } else {
            Err(self.errors)
        }
    }

    /// What the typed `weft` object needs, if the service uses a transport that has a TypeScript package.
    fn facade_plan(&self) -> Option<FacadePlan> {
        let mut plan = FacadePlan::default();
        for t in &self.options.transports {
            let library = t.library.as_deref();
            match (t.name.as_str(), library) {
                ("http", None | Some("express")) => plan.http = true,
                ("kafka", None | Some("kafkajs")) => plan.kafka = true,
                (name, lib) => plan.skipped.push(match lib {
                    Some(l) => format!("{name} ({l})"),
                    None => name.to_string(),
                }),
            }
        }
        if plan.http || plan.kafka {
            Some(plan)
        } else {
            None
        }
    }

    /// Names that cannot be written in TypeScript, reported together.
    fn check_names(&mut self) {
        let mut seen_packages = HashSet::new();
        for ir in self.irs {
            if !seen_packages.insert(ir.package.as_str()) {
                self.fail(
                    format!("package `{}` appears twice", ir.package),
                    "one IR per package",
                );
            }
            if RESERVED.contains(&ir.package.as_str()) {
                self.fail(
                    format!("the package name `{}` cannot be used in TypeScript", ir.package),
                    "rename the package; it would be a TypeScript keyword or a name the generated code uses",
                );
            }
            let type_names = ir.types.iter().map(|t| (&t.name, "type"));
            let error_names = ir.errors.iter().map(|e| (&e.name, "error"));
            for (name, what) in type_names.chain(error_names) {
                if RESERVED.contains(&name.as_str()) {
                    self.fail(
                        format!("the {what} name `{name}` in package `{}` cannot be used in TypeScript", ir.package),
                        "rename it; it would be a TypeScript keyword or a name the generated code uses",
                    );
                }
            }
            for t in &ir.types {
                for p in &t.params {
                    if RESERVED.contains(&p.as_str()) {
                        self.fail(
                            format!(
                                "the type parameter `{p}` of `{}` cannot be used in TypeScript",
                                t.name
                            ),
                            "rename it",
                        );
                    }
                }
            }
        }
    }

    fn package(&self, out: &mut String, ir: &Ir) {
        let _ = writeln!(out, "export namespace {} {{", ir.package);
        let mut first = true;
        let mut sep = |out: &mut String| {
            if !first {
                out.push('\n');
            }
            first = false;
        };
        for t in &ir.types {
            sep(out);
            self.type_def(out, &ir.package, t);
        }
        for e in &ir.errors {
            sep(out);
            self.error_def(out, &ir.package, e);
        }
        sep(out);
        self.events(out, ir);
        out.push_str("}\n");
    }

    fn type_def(&self, out: &mut String, pkg: &str, t: &TypeDef) {
        doc(out, 1, &t.doc, t.deprecated.as_deref());
        match &t.body {
            TypeBody::Enum { variants } => {
                // An enum is a union of its names. Per-value docs and deprecations go in a comment.
                for v in variants {
                    if !v.doc.is_empty() || v.deprecated.is_some() {
                        let mut parts = v.doc.clone();
                        if let Some(d) = &v.deprecated {
                            parts.push(format!("`{}` is deprecated{}", v.name, suffix(d)));
                        }
                        let _ = writeln!(out, "  // {}", parts.join(" "));
                    }
                }
                let union: Vec<String> =
                    variants.iter().map(|v| format!("\"{}\"", v.name)).collect();
                let _ = writeln!(out, "  export type {} = {};", t.name, union.join(" | "));
            }
            TypeBody::Record { fields } => {
                let _ = writeln!(
                    out,
                    "  export interface {}{} {{",
                    t.name,
                    generics(&t.params)
                );
                self.fields(out, pkg, fields);
                out.push_str("  }\n");
            }
        }
    }

    fn error_def(&self, out: &mut String, pkg: &str, e: &ErrorDef) {
        let mut d = e.doc.clone();
        d.push(format!("An error. HTTP status {}.", e.status));
        doc(out, 1, &d, None);
        let _ = writeln!(out, "  export interface {} {{", e.name);
        self.fields(out, pkg, &e.fields);
        out.push_str("  }\n");
    }

    fn fields(&self, out: &mut String, pkg: &str, fields: &[FieldDef]) {
        for f in fields {
            doc(out, 2, &f.doc, f.deprecated.as_deref());
            let ty = self.ty(&f.ty, pkg);
            if f.optional {
                let _ = writeln!(out, "    {}?: {ty} | null;", f.name);
            } else {
                let _ = writeln!(out, "    {}: {ty};", f.name);
            }
        }
    }

    /// Event name to payload type, for the facade to be typed from.
    fn events(&self, out: &mut String, ir: &Ir) {
        out.push_str("  /** Event name to payload type. */\n");
        if ir.events.is_empty() {
            out.push_str("  export interface Events {}\n");
            return;
        }
        out.push_str("  export interface Events {\n");
        for e in &ir.events {
            let _ = writeln!(
                out,
                "    \"{}\": {};",
                e.name,
                self.ty(&e.payload, &ir.package)
            );
        }
        out.push_str("  }\n");
    }

    fn ty(&self, ty: &TypeRef, pkg: &str) -> String {
        match ty {
            TypeRef::Primitive { name } => match name {
                Primitive::String | Primitive::Decimal => "string".into(),
                Primitive::Bool => "boolean".into(),
                Primitive::Int | Primitive::Int64 => match self.options.int64 {
                    Int64::Number => "number".into(),
                    Int64::Bigint => "bigint".into(),
                },
                Primitive::Int32 | Primitive::Float | Primitive::Float32 | Primitive::Float64 => {
                    "number".into()
                }
                Primitive::Uuid => "Uuid".into(),
                Primitive::Timestamp => "Date".into(),
                Primitive::Bytes => "Uint8Array".into(),
            },
            TypeRef::Named {
                package,
                name,
                args,
            } => {
                let mut s = if package == pkg {
                    name.clone()
                } else {
                    format!("{package}.{name}")
                };
                if !args.is_empty() {
                    let a: Vec<String> = args.iter().map(|a| self.ty(a, pkg)).collect();
                    let _ = write!(s, "<{}>", a.join(", "));
                }
                s
            }
            TypeRef::Param { name } => name.clone(),
            TypeRef::List { item } => format!("{}[]", self.ty(item, pkg)),
            TypeRef::Map { key, value } => {
                let v = self.ty(value, pkg);
                if self.is_enum(key) {
                    format!("Partial<Record<{}, {v}>>", self.ty(key, pkg))
                } else {
                    format!("Record<string, {v}>")
                }
            }
        }
    }

    /// The typed `weft` object: the maps of events and routes, and the code that wires the adapters.
    fn facade(&mut self, out: &mut String, plan: &FacadePlan) {
        out.push_str("\n// ---- The typed `weft` object ----\n");
        if !plan.skipped.is_empty() {
            let _ = writeln!(
                out,
                "// Not available in the TypeScript package yet, so not in `weft`: {}.",
                plan.skipped.join(", ")
            );
        }

        // Events, across every package. A name must mean one thing.
        let mut events: Vec<(String, String, String)> = Vec::new(); // name, type, package
        for ir in self.irs {
            for e in &ir.events {
                events.push((e.name.clone(), self.ty(&e.payload, ""), ir.package.clone()));
            }
        }
        for (i, (name, _, pkg)) in events.iter().enumerate() {
            if let Some((_, _, other)) = events[..i].iter().find(|(n, _, _)| n == name) {
                self.fail(
                    format!("the event `{name}` is declared in both `{other}` and `{pkg}`"),
                    "the typed `weft` object names events by their name alone: rename one",
                );
            }
        }
        if plan.kafka {
            out.push_str(
                "\n/** Every event, by name, with its payload type. */\nexport type Events = {\n",
            );
            for (name, ty, _) in &events {
                let _ = writeln!(out, "  \"{name}\": {ty};");
            }
            out.push_str("};\n");
        }

        if plan.http {
            let own = self.options.service.as_deref();
            out.push_str("\n/** The routes this service serves: those of its own package. */\nexport type HttpRoutes = {\n");
            for ir in self.irs.iter().filter(|i| Some(i.package.as_str()) == own) {
                self.route_entries(out, ir, "  ");
            }
            out.push_str("};\n");
            out.push_str("\n/** The routes of every package, for calling other services with `weft.http.to(name)`. */\nexport type HttpServices = {\n");
            for ir in self.irs {
                let _ = writeln!(out, "  {}: {{", ir.package);
                self.route_entries(out, ir, "    ");
                out.push_str("  };\n");
            }
            out.push_str("};\n");
        }

        let int64 = match self.options.int64 {
            Int64::Number => "number",
            Int64::Bigint => "bigint",
        };
        out.push_str("\n/** Builds the `weft` object from `weft.yaml` (or the config you pass). Import `weft` for the usual one. */\n");
        out.push_str("export function createWeft(options: { config?: Config } = {}) {\n");
        let _ = writeln!(
            out,
            "  const core = new Weft({{ contracts: new Contracts(contracts, {{ int64: \"{int64}\" }}), config: options.config ?? loadConfigSync() }});"
        );
        if plan.http {
            out.push_str("  const http = new Http(core, { adapter: expressAdapter() });\n");
        }
        if plan.kafka {
            out.push_str("  const kafka = new Messaging(core, { adapter: kafkaJsAdapter(), name: \"kafka\" });\n");
        }
        out.push_str("  return {\n");
        out.push_str("    /** Connects every transport. Register handlers first. */\n    start: () => core.start(),\n");
        out.push_str("    /** Stops taking new work, finishes what is running, and closes connections. */\n    stop: () => core.stop(),\n");
        out.push_str("    /** Middleware for every transport. */\n    use: (middleware: Middleware<Context>) => core.use(middleware),\n");
        out.push_str("    /** The untyped runtime underneath. */\n    core,\n");
        if plan.http {
            out.push_str(
                "    http: http as unknown as TypedHttp<HttpRoutes, HttpServices, Express>,\n",
            );
        }
        if plan.kafka {
            out.push_str("    kafka: kafka as unknown as TypedMessaging<Events, Kafka>,\n");
        }
        out.push_str("  };\n}\n\nlet current: ReturnType<typeof createWeft> | undefined;\n");
        out.push_str("/** The usual `weft` object. It is built from `weft.yaml` the first time it is used, so importing this file for its types needs no config. */\n");
        out.push_str("export const weft: ReturnType<typeof createWeft> = new Proxy({} as ReturnType<typeof createWeft>, {\n");
        out.push_str(
            "  get: (_target, key) => Reflect.get((current ??= createWeft()), key),\n});\n",
        );
    }

    /// One `"METHOD /path"` entry for each route of a package: by its full path, and by its path
    /// without the base when that is not taken by another route of the same method.
    fn route_entries(&self, out: &mut String, ir: &Ir, indent: &str) {
        for r in &ir.routes {
            let method = format!("{:?}", r.method).to_uppercase();
            let full = format!("{}{}", r.base.as_deref().unwrap_or(""), r.path);
            let shape = self.route_shape(ir, r);
            let _ = writeln!(out, "{indent}\"{method} {full}\": {shape};");
            if r.base.is_some() {
                let clash = ir.routes.iter().any(|o| {
                    o.name != r.name
                        && o.method == r.method
                        && format!("{}{}", o.base.as_deref().unwrap_or(""), o.path) == r.path
                });
                if !clash {
                    let _ = writeln!(out, "{indent}\"{method} {}\": {shape};", r.path);
                }
            }
        }
    }

    fn route_shape(&self, ir: &Ir, r: &weft_ir::RouteDef) -> String {
        let part = |t: &Option<TypeRef>| {
            t.as_ref()
                .map_or("undefined".to_string(), |t| self.ty(t, ""))
        };
        let params = if r.path_params.is_empty() {
            "undefined".to_string()
        } else {
            let fields: Vec<String> = r
                .path_params
                .iter()
                .map(|p| {
                    format!(
                        "{}{}: {}",
                        p.name,
                        if p.optional { "?" } else { "" },
                        self.ty(&p.ty, "")
                    )
                })
                .collect();
            format!("{{ {} }}", fields.join("; "))
        };
        let _ = ir;
        format!(
            "{{ body: {}; params: {params}; query: {}; headers: {}; result: {}; optional: {} }}",
            part(&r.body),
            part(&r.query),
            part(&r.headers),
            self.ty(&r.result.value, ""),
            r.result.optional
        )
    }

    fn is_enum(&self, ty: &TypeRef) -> bool {
        let TypeRef::Named { package, name, .. } = ty else {
            return false;
        };
        self.irs
            .iter()
            .filter(|i| i.package == *package)
            .flat_map(|i| &i.types)
            .any(|t| t.name == *name && matches!(t.body, TypeBody::Enum { .. }))
    }
}

#[derive(Default)]
struct FacadePlan {
    http: bool,
    kafka: bool,
    /// Configured transports that have no TypeScript package yet.
    skipped: Vec<String>,
}

impl FacadePlan {
    fn imports(&self, out: &mut String) {
        let mut core = vec!["Contracts"];
        if self.http {
            core.push("Http");
        }
        if self.kafka {
            core.push("Messaging");
        }
        core.extend([
            "Weft",
            "loadConfigSync",
            "type Config",
            "type Context",
            "type Middleware",
        ]);
        if self.http {
            core.push("type TypedHttp");
        }
        if self.kafka {
            core.push("type TypedMessaging");
        }
        let _ = writeln!(
            out,
            "import {{ {} }} from \"@weft-sdk/core\";",
            core.join(", ")
        );
        if self.http {
            out.push_str("import { expressAdapter } from \"@weft-sdk/http-express\";\n");
            out.push_str("import type { Express } from \"express\";\n");
        }
        if self.kafka {
            out.push_str("import { kafkaJsAdapter } from \"@weft-sdk/kafka-kafkajs\";\n");
            out.push_str("import type { Kafka } from \"kafkajs\";\n");
        }
    }
}

fn generics(params: &[String]) -> String {
    if params.is_empty() {
        String::new()
    } else {
        format!("<{}>", params.join(", "))
    }
}

fn suffix(message: &str) -> String {
    if message.is_empty() {
        String::new()
    } else {
        format!(": {message}")
    }
}

/// A JSDoc comment, or nothing when there is nothing to say.
fn doc(out: &mut String, depth: usize, lines: &[String], deprecated: Option<&str>) {
    let pad = "  ".repeat(depth);
    let mut text: Vec<String> = lines.iter().map(|l| l.replace("*/", "*\\/")).collect();
    if let Some(d) = deprecated {
        text.push(format!(
            "@deprecated{}",
            if d.is_empty() {
                String::new()
            } else {
                format!(" {}", d.replace("*/", "*\\/"))
            }
        ));
    }
    match text.as_slice() {
        [] => {}
        [one] => {
            let _ = writeln!(out, "{pad}/** {one} */");
        }
        many => {
            let _ = writeln!(out, "{pad}/**");
            for l in many {
                let _ = if l.is_empty() {
                    writeln!(out, "{pad} *")
                } else {
                    writeln!(out, "{pad} * {l}")
                };
            }
            let _ = writeln!(out, "{pad} */");
        }
    }
}
