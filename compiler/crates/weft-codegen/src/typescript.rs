//! TypeScript output: `weft.gen.ts`.
//!
//! The file has, in order: a header, the `Uuid` brand, one type-only `namespace` per package (enums as string
//! unions, records as interfaces, errors as interfaces, an `Events` map), and the checked IR of every package as a
//! constant for the runtime to read ([ADR 0021](../../../../docs/decisions/0021-generated-code-embeds-the-ir.md)).

use std::collections::HashSet;
use std::fmt::Write;

use weft_ir::{ErrorDef, FieldDef, Ir, Primitive, TypeBody, TypeDef, TypeRef};

use crate::{CodegenError, Int64, Options};

/// Words that cannot name a package, a type or a type parameter in TypeScript, or that the generated code itself
